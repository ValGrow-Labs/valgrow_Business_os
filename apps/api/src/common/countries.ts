export const DEFAULT_COUNTRY = "India";

const COUNTRY_MAP = new Map<string, CountryData>();
COUNTRIES.forEach((c) => {
  COUNTRY_MAP.set(c.name.toLowerCase(), c);
  COUNTRY_MAP.set(c.code.toLowerCase(), c);
  COUNTRY_MAP.set(c.officialName.toLowerCase(), c);
  c.aliases?.forEach((a) => COUNTRY_MAP.set(a.toLowerCase(), c));
});

export function findCountry(
  nameOrCode?: string | null,
): CountryData | undefined {
  if (!nameOrCode) return undefined;
  return COUNTRY_MAP.get(nameOrCode.trim().toLowerCase());
}

export function isValidCountry(nameOrCode?: string | null): boolean {
  return Boolean(findCountry(nameOrCode));
}
